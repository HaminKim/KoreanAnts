def default_area(city, emd):
    """AREAS 에 없는 행정동의 기본 생활권"""
    if emd.endswith("읍"):
        return emd
    if emd.endswith("면"):
        return "면 지역"
    return f"{city.rstrip('시군')} 시내" if city.endswith("시") else "기타"


def areas_of(sggcd, city, emds):
    """{생활권: [행정동]} — 화면 순서. 하나뿐이면 None (나누지 않음)"""
    rule = AREAS.get(sggcd, (city, {}))[1]
    known = {e: a for a, es in rule.items() for e in es}
    unknown = [e for es in rule.values() for e in es if e not in emds]
    if unknown:
        raise ValueError(f"{city}: 행정동 이름 확인 필요 {unknown}")
    out = {a: [] for a in rule}
    for e in emds:
        out.setdefault(known.get(e) or default_area(city, e), []).append(e)
    out = {a: es for a, es in out.items() if es}
    # '면 지역'·'기타' 는 맨 뒤로
    out = dict(sorted(out.items(), key=lambda kv: kv[0] in ("면 지역", "기타")))
    return out if len(out) > 1 else None
